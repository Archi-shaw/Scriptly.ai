// Test-only OpenAI-compatible server used by the end-to-end suite.
// It is never used by the application itself; the app talks to it only when
// OPENAI_BASE_URL points here during `npm run test:e2e`.
import http from "node:http";

const port = Number(process.env.MOCK_OPENAI_PORT ?? 4107);
const expectedKey = process.env.MOCK_OPENAI_KEY ?? "test-openai-key";
let requests = [];

function send(res, status, body, headers = {}) {
  res.writeHead(status, { "Content-Type": "application/json", ...headers });
  res.end(JSON.stringify(body));
}

function completion(content, model) {
  return {
    id: `chatcmpl-${Date.now()}`,
    object: "chat.completion",
    model,
    choices: [{ index: 0, message: { role: "assistant", content }, finish_reason: "stop" }],
    usage: { prompt_tokens: 42, completion_tokens: 64, total_tokens: 106 },
  };
}

const server = http.createServer(async (req, res) => {
  if (req.url === "/__requests" && req.method === "GET") return send(res, 200, requests);
  if (req.url === "/__requests" && req.method === "DELETE") {
    requests = [];
    return send(res, 200, { cleared: true });
  }
  if (req.url !== "/v1/chat/completions" || req.method !== "POST") return send(res, 404, { error: { message: "Not found" } });

  let raw = "";
  for await (const chunk of req) raw += chunk;
  const body = JSON.parse(raw || "{}");
  requests.push(body);

  if (req.headers.authorization !== `Bearer ${expectedKey}`) {
    return send(res, 401, { error: { message: "Incorrect API key provided", code: "invalid_api_key" } });
  }

  const prompt = body.messages?.find((m) => m.role === "user")?.content ?? "";
  if (prompt.includes("[[mock:500]]")) return send(res, 500, { error: { message: "The server had an error" } });
  if (prompt.includes("[[mock:empty]]")) return send(res, 200, completion("", body.model));

  const language = prompt.match(/- Language: (.+)/)?.[1] ?? "unknown";
  let content;
  const isRefine = prompt.includes("\n<content>\n");
  if (prompt.includes("===VERSION===")) {
    content = "First alternative version.\n===VERSION===\nSecond alternative version.\n===VERSION===\nThird alternative version.";
  } else if (isRefine && prompt.startsWith("# Task\nContinue the content")) {
    content = "This is the continuation written by the mock model.";
  } else if (isRefine) {
    content = "Refined content from the mock model.";
  } else if (prompt.startsWith("# Task\n")) {
    const task = prompt.split("\n")[1] ?? "";
    content = `# Mock result\n\nThis content was generated by the test model.\n\n- Task: ${task}\n- ${language}`;
  } else {
    content = "Refined content from the mock model.";
  }
  return send(res, 200, completion(content, body.model ?? "mock-model"));
});

server.listen(port, "127.0.0.1", () => console.log(`[mock-openai] listening on ${port}`));
